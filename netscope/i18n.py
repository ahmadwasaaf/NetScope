AR_MONTHS = ["يناير", "فبراير", "مارس", "أبريل", "مايو", "يونيو", "يوليو",
             "أغسطس", "سبتمبر", "أكتوبر", "نوفمبر", "ديسمبر"]
EN_MONTHS = ["January", "February", "March", "April", "May", "June", "July",
             "August", "September", "October", "November", "December"]


class Translator:
    def __init__(self, lang: str = "en"):
        self.lang = lang if lang in STRINGS else "en"

    def __call__(self, key: str, **kw) -> str:
        text = STRINGS[self.lang].get(key) or STRINGS["en"].get(key, key)
        return text.format(**kw) if kw else text

    @property
    def rtl(self) -> bool:
        return self.lang == "ar"

    def date(self, d) -> str:
        months = AR_MONTHS if self.lang == "ar" else EN_MONTHS
        text = f"{d.day} {months[d.month - 1]} {d.year}" if self.lang == "ar" \
            else f"{months[d.month - 1]} {d.day}, {d.year}"
        if getattr(d, "hour", 0) or getattr(d, "minute", 0):
            text += f" · {d.hour:02d}:{d.minute:02d}"
        return text
